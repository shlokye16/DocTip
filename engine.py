"""Conversation engine for the voice reasoning check.

Flow, two phases:
1. visit: the app listens. When a flagged disease (diseases/*.json) is mentioned, it returns
   ONE short tip for the clinician (max MAX_TIPS per visit) and otherwise stays silent. The
   patient is never interrupted with questions.
2. debrief: after end_visit(), the assistant asks up to 3 Socratic questions, judges whether
   each answer gives specific objective reasoning (one gentle follow-up max per question),
   then closes and produces a reasoning note.

Design choices:
- Question wording lives in reviewed JSON profiles, NOT generated by the LLM (less
  hallucination risk for clinical content).
- The LLM is used only to judge answers. If it is unavailable, a heuristic judge is used.
- The assistant stays silent unless a flagged disease is mentioned (avoids alert fatigue).

Synthetic demo. Not a diagnostic tool. Clinical content in profiles is DRAFT and needs
clinician review before any real use.
"""
import json
import re
import time
from dataclasses import dataclass, field
from pathlib import Path

DISEASE_DIR = Path(__file__).parent / "diseases"
PROFILE_DIR = DISEASE_DIR if DISEASE_DIR.is_dir() else Path(__file__).parent
MAX_QUESTIONS = 3
MAX_TIPS = 3  # per visit, to avoid alert fatigue


# ---------------------------------------------------------------- profiles
def load_profiles(dirpath=None):
    profiles = {}
    source_dir = Path(dirpath) if dirpath is not None else PROFILE_DIR
    for p in sorted(source_dir.glob("*.json")):
        d = json.loads(p.read_text())
        if isinstance(d, dict) and d.get("id") and isinstance(d.get("questions"), list):
            profiles[d["id"]] = d
    return profiles


def match_profile(profiles, text):
    """Return the flagged-disease profile to use, else None.
    Higher "priority" wins (a named disease beats a symptom-level trigger); ties go to the
    profile mentioned earliest."""
    best = None
    for d in profiles.values():
        pos = None
        for t in d.get("triggers", []):
            m = re.search(r"\b" + re.escape(t) + r"\b", text, re.I)
            if m:
                pos = m.start() if pos is None else min(pos, m.start())
        for t in d.get("abbreviations", []):  # case-sensitive (e.g., MI, SCD)
            m = re.search(r"\b" + re.escape(t) + r"\b", text)
            if m:
                pos = m.start() if pos is None else min(pos, m.start())
        key = (-d.get("priority", 0), pos) if pos is not None else None
        if key is not None and (best is None or key < best[0]):
            best = (key, d)
    return best[1] if best else None


def find_concerns(profile, text):
    return [c for c in profile.get("concern_patterns", []) if re.search(c["pattern"], text, re.I)]


def visit_context(profiles, recent, text):
    """Use affirmative encounter clauses for matching. Keep the original transcript for notes."""
    clauses = re.split(r"[.!?;\n]|\b(?:but|however)\b", text, flags=re.I)
    active = []
    excluded = set()
    for clause in clauses:
        if not clause.strip():
            continue
        clause = re.sub(r"\bsickle[- ]cell trait\b|\b(?:hearing|walking|mobility) aids\b|\b(?:ST[- ]segment|ST|respiratory) depression\b", "", clause, flags=re.I)
        profile = match_profile(profiles, clause)
        if re.search(r"\b(?:family history|mother has|father has|sister has|brother has|ruled out|negative for|no evidence of|denies|does not have|doesn't have|no longer suspect|hypothetically)\b|\bno\s+(?:history of\s+)?(?:sickle|chest pain|depression|hiv|tb|tuberculosis|endometriosis|preeclampsia|heart disease)\b", clause, re.I):
            if profile:
                excluded.add(profile["id"])
                active = [part for part in active if not match_profile({profile["id"]: profile}, part)]
            continue
        if profile:
            old = match_profile(profiles, ". ".join(active))
            if old and old["id"] != profile["id"]:
                active.clear()
        active.append(clause.strip())
    current = ". ".join(active)
    named = match_profile(profiles, current)
    if named or not current:
        return named, current, excluded
    context = " ".join([*recent, current]).lower()
    candidates = []
    for profile in profiles.values():
        groups = profile.get("context_cues", [])
        if groups and all(any(re.search(r"\b" + re.escape(cue) + r"\b", context)
                              for cue in group) for group in groups):
            if any(cue in current.lower() for group in groups for cue in group):
                candidates.append(profile)
    return candidates[0] if len(candidates) == 1 else None, current, excluded


def visit_concerns(profile, text):
    concerns = []
    for concern in profile.get("concern_patterns", []):
        for clause in re.split(r"[.!?;\n]|\bbut\b", text, flags=re.I):
            if re.search(r"\bstress (?:test|echo)|\b(?:vaginal|nasal|wound) discharge\b", clause, re.I):
                continue
            match = re.search(concern["pattern"], clause, re.I)
            if match and not re.search(
                r"\b(?:not|never|isn't|is not|avoid|without|no evidence of|denies)\b(?:\s+[\w'-]+){0,4}\s*$",
                clause[:match.start()], re.I
            ):
                concerns.append(concern)
                break
    return concerns


def match_fhir_conditions(profiles, prefetch):
    """For the CDS Hooks endpoint: which flagged profiles match a prefetched Condition bundle?"""
    found = {}
    bundle = (prefetch or {}).get("conditions") or {}
    for entry in bundle.get("entry", []):
        res = entry.get("resource", {})
        code = res.get("code", {}) or {}
        texts = [code.get("text", "")]
        for c in code.get("coding", []) or []:
            texts.append(c.get("display", ""))
            cid = (c.get("code") or "").upper()
            for d in profiles.values():
                if any(cid.startswith(p.upper()) for p in d.get("icd10_prefixes", [])):
                    found[d["id"]] = d
        d = match_profile(profiles, " ; ".join(t for t in texts if t))
        if d:
            found[d["id"]] = d
    return list(found.values())


# ---------------------------------------------------------------- context extraction
def extract_context(text):
    ctx = {}
    m = re.search(r"(\d{1,3})[- ]?(?:year|yr)s?[- ]?old|\b(\d{1,3})\s?(?:y/o|yo)\b", text, re.I)
    if m:
        ctx["age"] = int(m.group(1) or m.group(2))
    if re.search(r"\b(?:woman|female|girl|lady)\b", text, re.I):
        ctx["sex"] = "woman"
    elif re.search(r"\b(?:man|male|boy|gentleman)\b", text, re.I):
        ctx["sex"] = "man"
    race_patterns = [
        ("Black", r"\bblack (?:man|woman|male|female|patient|adult|child|boy|girl)\b|african[- ]american"),
        ("white", r"\bwhite (?:man|woman|male|female|patient|adult|child|boy|girl)\b|\bcaucasian\b"),
        ("Hispanic/Latino", r"\bhispanic\b|\blatin[oax]\b"),
        ("Asian", r"\basian (?:man|woman|male|female|patient|adult|child|boy|girl)\b"),
    ]
    for label, pat in race_patterns:
        if re.search(pat, text, re.I):
            ctx["race"] = label
            break
    ins = re.search(r"\b(medicaid|medicare|uninsured|private insurance)\b", text, re.I)
    if ins:
        ctx["insurance"] = ins.group(1).lower()
    return ctx


def describe_context(ctx):
    if not ctx:
        return "not stated"
    parts = []
    if "age" in ctx:
        parts.append(f"{ctx['age']}-year-old")
    if "race" in ctx:
        parts.append(ctx["race"])
    parts.append(ctx.get("sex", "patient"))
    s = " ".join(parts)
    if "insurance" in ctx:
        s += f" ({ctx['insurance']})"
    return s


# ---------------------------------------------------------------- judging
JUDGE_SYSTEM = """You review a clinician's spoken answer to a bias-awareness question about {disease}.
Decide whether it gives specific, objective, patient-specific clinical reasoning (findings,
history, labs, guidelines, timing) rather than vague, stereotyped, or demographic-based
reasoning. Be warm, indirect, and collegial. Prefer gentle phrasing such as "Could we briefly review..." Never accuse anyone of bias, never diagnose, never recommend treatment.
Return JSON: {{"sufficient": true or false, "message": "if insufficient, ONE short gentle
follow-up question in spoken style; otherwise an empty string"}}"""


def llm_judge(profile, question, answer):
    from llm import chat_json  # lazy: tests and offline demos don't need the API
    return chat_json(
        JUDGE_SYSTEM.format(disease=profile["name"]),
        json.dumps({"question": question["text"], "answer": answer}),
    )


def heuristic_judge(profile, question, answer):
    words = len(answer.split())
    has_term = any(re.search(r"\b" + re.escape(t), answer, re.I) for t in profile.get("evidence_terms", []))
    ok = words >= question.get("min_words", 12) and has_term
    return {"sufficient": ok, "message": question.get("followup", "")}


# ---------------------------------------------------------------- session + engine
@dataclass
class Session:
    id: str
    created: float = field(default_factory=time.time)
    profile_id: str | None = None
    context: dict = field(default_factory=dict)
    initial_statement: str = ""
    concerns: list = field(default_factory=list)   # concern ids surfaced
    queue: list = field(default_factory=list)      # question dicts, max MAX_QUESTIONS
    qi: int = 0
    followup_used: bool = False
    pending: str = ""                              # first answer, when a follow-up was asked
    qa: list = field(default_factory=list)
    addenda: list = field(default_factory=list)
    closed: bool = False
    phase: str = "visit"                           # visit -> debrief -> (closed)
    tips: list = field(default_factory=list)       # tip ids already shown this visit
    quick_reflection: bool = False
    recent_turns: list = field(default_factory=list)
    turns_since_anchor: int = 0


class Engine:
    def __init__(self, profiles, judge=None):
        self.profiles = profiles
        self.judge = judge  # judge(profile, question, answer) -> dict or None

    # ---- public
    def turn(self, s, text):
        text = (text or "").strip()
        if not text:
            return self._resp(s, None)
        s.context.update(extract_context(text))
        if s.closed:  # clinician revised their plan after the check
            s.addenda.append(text)
            return self._resp(s, "Added to the note.")
        return self._visit_turn(s, text) if s.phase == "visit" else self._debrief_turn(s, text)

    def end_visit(self, s, quick=False):
        """Visit is over: start the longer conversation (or close quietly if nothing was flagged)."""
        if s.closed or s.phase != "visit":
            return self._resp(s, None)
        prof = self.profiles.get(s.profile_id) if s.profile_id else None
        if not prof:
            s.closed, s.phase = True, "closed"
            return self._resp(s, "Visit ended. Nothing was flagged.")
        if quick:
            s.quick_reflection = True
            s.phase = "debrief"
            s.queue = [{"text": q, "options": options} for q, options in [
                ("What guided your assessment?", prof["reflection_choices"] + ["Other", "Still assessing"]),
                ("Same findings, different background: same plan?", ["Yes", "I would reconsider", "Unsure"])
            ]]
            return self._resp(s, "Quick reflection")
        found = [c for c in prof.get("concern_patterns", []) if c["id"] in s.concerns]
        s.queue, s.qi, s.phase = self._build_queue(prof, found), 0, "debrief"
        return self._resp(s, f"Now that the visit is over, a few questions about the {prof['name'][0].lower() + prof['name'][1:]} plan. "
                             + s.queue[0]["text"])

    # ---- phase handlers
    def _visit_turn(self, s, text):
        """During the visit: at most one short tip per turn, never a question."""
        topic_change = re.search(r"\b(?:different patient|another patient|changing (?:the )?subject|unrelated (?:issue|problem)|separately)\b", text, re.I)
        if topic_change:
            s.recent_turns.clear()
            s.turns_since_anchor = 3
        detected, current, excluded = visit_context(self.profiles, s.recent_turns, text)
        if s.profile_id in excluded:
            s.profile_id = None
            s.concerns.clear()
        if excluded:
            s.recent_turns.clear()
        if not current:
            return self._resp(s, None)
        previous = s.recent_turns[-1:] if not s.profile_id and not topic_change else []
        s.recent_turns = (s.recent_turns + [current])[-3:]
        first = detected is not None and detected["id"] != s.profile_id
        if detected:
            s.turns_since_anchor = 0
        else:
            s.turns_since_anchor += 1
        prof = detected or self.profiles.get(s.profile_id)
        if s.turns_since_anchor > 2 and not detected:
            return self._resp(s, None)
        if not prof:
            return self._resp(s, None)  # stay quiet unless a flagged disease is mentioned
        if first:
            s.recent_turns = [current]
            s.concerns.clear()
            s.profile_id, s.initial_statement = prof["id"], text
        matched = visit_concerns(prof, ". ".join([*previous, current]))
        s.concerns += [c["id"] for c in matched if c["id"] not in s.concerns]
        tip = None
        if len(s.tips) < MAX_TIPS:
            for c in matched:
                tip_id = (prof["id"], c["id"])
                if c.get("tip") and tip_id not in s.tips:
                    s.tips.append(tip_id)
                    tip = c["tip"]
                    break
        return self._resp(s, tip, just_flagged=first and tip is not None)

    def _debrief_turn(self, s, text):
        prof = self.profiles[s.profile_id]
        q = s.queue[s.qi]
        combined = (s.pending + " " + text).strip() if s.followup_used else text
        verdict = self._judge(prof, q, combined)

        for c in find_concerns(prof, text):  # new concern voiced during an answer
            if c["id"] not in s.concerns:
                s.concerns.append(c["id"])
                self._insert_concern(s, c)

        if not verdict["sufficient"] and not s.followup_used:
            s.followup_used = True
            s.pending = combined
            return self._resp(s, verdict["message"] or q["followup"])

        s.qa.append({"id": q["id"], "question": q["text"], "answer": combined,
                     "specific": bool(verdict["sufficient"])})
        s.followup_used, s.pending = False, ""
        s.qi += 1
        if s.qi < len(s.queue):
            return self._resp(s, "Thanks. " + s.queue[s.qi]["text"])

        s.closed, s.phase = True, "closed"
        weak = any(not a["specific"] for a in s.qa)
        msg = "Thanks. I've logged your reasoning."
        if weak:
            msg += " A couple of answers were brief, so you may want to add detail to the note."
        return self._resp(s, msg + " You can review the note any time.")

    # ---- internals
    def _build_queue(self, prof, found_concerns):
        concern_qs = [dict(c, kind="concern", text=c["question"]) for c in found_concerns[:2]]
        base = prof["questions"]
        cf = [q for q in base if q.get("kind") == "counterfactual"]
        others = [q for q in base if q.get("kind") != "counterfactual"]
        room = MAX_QUESTIONS - len(concern_qs) - len(cf)
        return concern_qs + others[:max(room, 0)] + cf

    def _insert_concern(self, s, c):
        """A new concern surfaced mid-conversation: swap it in for an unasked base question."""
        for i in range(len(s.queue) - 1, s.qi, -1):
            if s.queue[i].get("kind") == "base":
                del s.queue[i]
                s.queue.insert(s.qi + 1, dict(c, kind="concern", text=c["question"]))
                return

    def _judge(self, prof, q, answer):
        if self.judge:
            try:
                r = self.judge(prof, q, answer)
                if isinstance(r, dict) and "sufficient" in r:
                    return {"sufficient": bool(r["sufficient"]), "message": str(r.get("message") or "")}
            except Exception as e:  # no key, bad JSON, timeout...
                print("LLM judge unavailable, using heuristic:", e)
        return heuristic_judge(prof, q, answer)

    def _resp(self, s, reply, just_flagged=False):
        prof = self.profiles.get(s.profile_id) if s.profile_id else None
        return {
            "reply": reply,
            "flagged": prof is not None,
            "just_flagged": just_flagged,
            "phase": s.phase,
            "disease": {"id": prof["id"], "name": prof["name"]} if prof else None,
            "question_index": min(s.qi + 1, len(s.queue)) if prof else 0,
            "total_questions": len(s.queue),
            "done": s.closed,
            "reflection": s.queue if s.quick_reflection and not s.closed else None,
            "note": build_note(s, prof)["text"] if (prof and s.closed) else None,
        }


# ---------------------------------------------------------------- reasoning note
def build_note(s, prof):
    stamp = time.strftime("%Y-%m-%d %H:%M", time.localtime(s.created))
    names = {c["id"]: c for c in prof.get("concern_patterns", [])}
    lines = [
        "REASONING CHECK LOG (decision-support, synthetic demo)",
        f"Date/time: {stamp}",
        f"Condition flagged: {prof['name']}",
        f"Patient as described by clinician: {describe_context(s.context)}",
        f'Clinician\'s initial statement: "{s.initial_statement}"',
    ]
    if s.concerns:
        lines.append("Concerns surfaced: " + "; ".join(names[c]["id"].replace("_", " ") for c in s.concerns if c in names))
    lines.append("")
    for i, a in enumerate(s.qa, 1):
        lines += [f"Q{i}: {a['question']}",
                  f"A{i}: {a['answer']}"]
        if "specific" in a:
            lines.append(f"   (answer judged {'specific' if a['specific'] else 'brief or non-specific'})")
    if s.addenda:
        lines += ["", "Addenda after the check:"] + [f"- {t}" for t in s.addenda]
    lines += ["", f"Reference: {prof.get('guideline_note', '')}",
              "This tool prompts reasoning only. It does not diagnose or recommend treatment."]
    text = "\n".join(lines)
    data = {
        "created": s.created, "condition": prof["id"], "context": s.context,
        "initial_statement": s.initial_statement, "concerns": s.concerns,
        "qa": s.qa, "addenda": s.addenda, "closed": s.closed,
    }
    return {"text": text, "json": data}
